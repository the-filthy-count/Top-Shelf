const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const code = fs.readFileSync('static/queue.js', 'utf8');
const performer = {id:'site-id', name:'Bella Nova', gender:'FEMALE', parent:{id:'canonical-id'}};
const scene = {id:'scene-id', performers:[{performer}], _source:'TPDB', studio:{id:'studio-id',name:'Studio'}};
const ctx = vm.createContext({_qStoredMatchScene:{id:scene.id,source:'TPDB',performers:'Bella Nova',_raw:scene}});
const start = code.indexOf('  function _qsBuildStoredMatchResult()');
const end = code.indexOf('  // Render the stored-match row',start);
vm.runInContext(code.slice(start,end),ctx);
const result = vm.runInContext('_qsBuildStoredMatchResult()',ctx);
assert.equal(result._raw.performers[0].performer.id,'site-id');
assert.equal(result._raw.performers[0].performer.parent.id,'canonical-id');
assert.equal(result._raw._source,'TPDB');
ctx.scene=result._raw;
const castStart=code.indexOf('    _qConfirmPerformers = (scene.performers');
const castEnd=code.indexOf('    _qConfirmChecked',castStart);
vm.runInContext(code.slice(castStart,castEnd),ctx);
ctx.pillNames=['Bella Nova','Typed name'];
const submitStart=code.indexOf('    const perfByName = new Map();');
const submitEnd=code.indexOf("    const titleEl",submitStart);
vm.runInContext(code.slice(submitStart,submitEnd)+'\nglobalThis.submitted = chosen;',ctx);
assert.equal(ctx.submitted[0].performer.parent.id,'canonical-id');
assert.equal(ctx.submitted[0].performer.gender,'FEMALE');
assert.equal(ctx.submitted[1].performer.id,'');
console.log('Stored match identity survives result reconstruction and filing');
