const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('static/queue.js','utf8');
const start = source.indexOf('  function _qsPhashComparison(row)');
const end = source.indexOf('  function _qsPhashIndicator(row)',start);
const ctx = vm.createContext({_qSearchRecord:{technical:{phash:'0000000000000000'}}});
vm.runInContext(source.slice(start,end),ctx);
const compare = fp => ctx._qsPhashComparison({_raw:{fingerprints:fp}});
assert.equal(compare([{algorithm:'PHASH',hash:'0000000000000000'}]).state,'exact');
assert.equal(compare([{algorithm:'PHASH',hash:'0000000000000fff'}]).state,'close');
assert.equal(compare([{algorithm:'PHASH',hash:'0000000000001fff'}]).state,'different');
assert.equal(compare([{algorithm:'OSHASH',hash:'0000000000000000'}]).state,'unknown');
assert.equal(compare([]).state,'unknown');
assert.equal(compare([{algorithm:'PHASH',hash:'bad'}]).state,'unknown');
assert.equal(compare({PHASH:'0000000000000001'}).state,'close');
assert.equal(compare([{algorithm:'PHASH',hash:'ffffffffffffffff'},{algorithm:'PHASH',hash:'0000000000000000'}]).state,'exact');
ctx._qSearchRecord=null;
assert.equal(compare([{algorithm:'PHASH',hash:'0000000000000000'}]).state,'unknown');
console.log('Fingerprint indicator checks passed');
